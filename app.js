function NotificationsPage({ notices, markAll, openNotice }) {
    const [query, setQuery] = React.useState(""), [filter, setFilter] = React.useState("All");
    const list = notices.filter(n => (n.description + " " + n.meta).toLowerCase().includes(query.toLowerCase()) && (filter === "All" || (filter === "Unread" && !n.read) || (filter === "Submissions" && n.type.includes("SUBMISSION")) || (filter === "Document Requests" && n.type.includes("REQUEST")) || (filter === "Revisions" && n.type.includes("REVISION")) || (filter === "Approvals" && n.type.includes("APPROVED"))));
    return React.createElement(React.Fragment, null,
        React.createElement(PageHead, { title: "Notifications", subtitle: "Stay updated on document submissions, requests, revisions, and approvals for Bachelor of Science in Information Technology.", action: React.createElement("button", { className: "btn secondary", onClick: markAll }, "Mark all as read") }),
        React.createElement("section", { className: "card notifications-page" },
            React.createElement("div", { className: "notification-tools" },
                React.createElement("div", { className: "search" },
                    "\u2315 ",
                    React.createElement("input", { value: query, onChange: e => setQuery(e.target.value), placeholder: "Search notifications..." })),
                React.createElement("select", { value: filter, onChange: e => setFilter(e.target.value) },
                    React.createElement("option", null, "All"),
                    React.createElement("option", null, "Unread"),
                    React.createElement("option", null, "Submissions"),
                    React.createElement("option", null, "Document Requests"),
                    React.createElement("option", null, "Revisions"),
                    React.createElement("option", null, "Approvals"))),
            React.createElement("div", { className: "notification-list" }, list.map(n => React.createElement("article", { className: `notice-row ${n.read ? "read" : "unread"}`, key: n.id },
                React.createElement("i", { className: "unread-dot" }),
                React.createElement("span", { className: `notice-page-icon ${n.icon}` },
                    React.createElement(UiIcon, { name: n.icon })),
                React.createElement("div", null,
                    React.createElement("b", null, n.type),
                    React.createElement("h3", null, n.description),
                    React.createElement("p", null, n.meta),
                    React.createElement("time", null, n.date)),
                React.createElement("button", { className: "btn secondary", onClick: () => openNotice(n) }, n.target === "requestDetail" ? "View Request" : n.type.includes("REVISION") ? "View Revision" : "View Document")))),
            list.length === 0 && React.createElement("div", { className: "empty" },
                React.createElement("b", null, "No notifications found"),
                React.createElement("p", null, "Try changing your search or filter."))));
}
